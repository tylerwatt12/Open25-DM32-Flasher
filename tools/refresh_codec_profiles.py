"""Refresh DM32-only codec metadata from the reviewed RadioFoundry source pin."""
import argparse
import ast
import json
import subprocess
from pathlib import Path

PIN = '88283f6ce3aab4c5ff5c9995600de2acfa2c6f7b'
APP = Path(__file__).resolve().parents[1]


def profiles(source):
    values = {}
    class Constants(ast.NodeTransformer):
        def visit_Name(self, node):
            return ast.parse(repr(values[node.id]), mode='eval').body if node.id in values else node
    tree = ast.parse((source / 'tools/hrc7000_codec.py').read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            key = node.targets[0].id
            if key in ('ENTRIES_049', 'PROFILES'):
                values[key] = ast.literal_eval(Constants().visit(node.value))
    maps = [json.loads(p.read_text()) for p in
            (source / 'tools/rfoundry/rfoundry/codec_maps/dm32').glob('*.json')]
    number = lambda v: int(v, 0) if isinstance(v, str) else v
    out = []
    for p in values['PROFILES'].values():
        if p['board'] != 'dm32':
            continue
        m, = [m for m in maps if m['code']['sha256'] == p['code_sha256']]
        assert number(m['code']['run']) == p['code'][2] and m['code']['len'] == p['code'][1]
        assert not m['island_ptrs'] and not m['branches']
        assert all(r['kind'] == 'word' for r in m['self_refs'])
        out.append(dict(name=p['name'], tag=p['tag'], code=p['code'][0] - 0x03000000,
                        codeLength=p['code'][1], codeRam=p['code'][2], sha256=p['code_sha256'],
                        tables=p['tables'][0] - 0x03000000, tablesLength=p['tables'][1],
                        tablesRam=p['tables'][2], tablesSha256=p['tables_sha256'],
                        entries=[p['entries'][k] for k in ('decode', 'encode', 'dec_init', 'dec_set', 'enc_init', 'enc_set', 'fec_init')],
                        relocations=sorted([[number(r['off']), number(r['value'])] for r in m['self_refs']])))
    return out


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Reviewed upstream source at the pin named in this file')
    args = parser.parse_args()
    if subprocess.check_output(['git','-C',str(args.source),'rev-parse','HEAD'],text=True).strip()!=PIN:
        raise SystemExit('Refusing metadata from an unreviewed upstream revision')
    if subprocess.check_output(['git','-C',str(args.source),'status','--porcelain','--untracked-files=no'],text=True).strip():
        raise SystemExit('Preserving changed upstream source; expected a clean pinned checkout')
    body = ('// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 The RadioFoundry Authors\n'
            '// Generated by tools/refresh_codec_profiles.py from RadioFoundry ' + PIN + '.\n'
            '// Metadata only; codec bytes are read from the connected radio.\n'
            'export const OEM_CODECS = ' + json.dumps(profiles(args.source), indent=2) + ';\n')
    for folder in ('lib', 'v3/lib'):
        (APP / folder / 'dm32-codec-profiles.mjs').write_text(body)
